/**
 * PHASE 8D-3A production — non-settlement POI place-name component
 * pools for `names/poi-place-name-generator.js`.
 *
 * A POI is not always a settlement (`data/settlement-name-components.js`'s
 * `SETTLEMENT_NAME_ROOTS` already covers that case for POI templates
 * whose canonical type is `city`) -- a natural feature, an
 * installation, or a city district each read more naturally with
 * their own naming flavor than "Kalhaven <Label>". These three pools
 * back that split (see `poi-place-name-generator.js`'s
 * `poiNameStyleForType()`):
 *
 *  - `GEOGRAPHIC_FEATURE_NOUNS` (90 entries) pairs with the EXISTING
 *    `ship-name-adjectives.js` pool (145 entries, reused rather than
 *    duplicated -- an evocative adjective like "Ancient"/"Shattered"/
 *    "Whispering" suits a canyon or a ruin exactly as well as it
 *    suits a starship) to combinatorially name Wilderness/Ancient-
 *    Force-category POIs (a Waterfall, a Sith Tomb, a Canyon
 *    Overlook, ...) -- e.g. "Shattered Ridge", "Whispering Hollow".
 *  - `FACILITY_DESIGNATIONS` (160 entries) names Industrial/Research/
 *    Military/installation-category POIs (a Mine, a Research
 *    Facility, a Garrison, ...) with institutional designation
 *    strings -- e.g. "Site 7", "Installation Gamma".
 *  - `DISTRICT_DESCRIPTORS` (109 entries) names Civic/Trade/Criminal
 *    region-category POIs (a Market District, an Undercity Slum, a
 *    Warehouse District, ...) with evocative quarter/ward names --
 *    e.g. "the Ashfall Quarter", "Lowtown".
 *
 * `tags` reuse the same free-text biome/character vocabulary as every
 * other Phase 8D naming pool, so `weightedPickWithPreference()` can
 * softly bias a pick toward the parent planet's/POI's own context.
 */

