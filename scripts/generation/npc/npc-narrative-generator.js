/**
 * PHASE 8D-2 foundation — NPC narrative-facts generator.
 *
 * Fills exactly the fields `npc-concept.js`'s schema already reserves
 * for narrative color (`appearance`/`personality`/`motivation`/
 * `mannerisms`/`agenda`/`secret`/`situation`/`suggestion` — see that
 * file's header for the `hook` vs `situation` and `motivation` vs
 * `agenda` distinctions) -- this module owns none of that schema
 * itself, it only rolls values FOR it. `name`/`speciesId`/
 * `factionId`/`linkedLocationId`/mechanical-adjacent fields all stay
 * entirely caller-supplied, exactly as `npc-concept.js` already
 * requires (this module never invents a canonical reference).
 *
 * `suggestion` is explicitly SUGGEST-tier only: a short, GM-facing
 * possible use for this NPC, generated by lightly combining the
 * rolled personality + motivation -- never a link to any statblock,
 * mechanic, or canonical record. The hard rule restated: "Generate
 * narrative facts. Suggest canonical mechanics. Resolve through
 * existing authorities."
 */

import { NPC_APPEARANCE_TRAITS } from '../data/npc-appearance-traits.js';
import { NPC_PERSONALITY_TRAITS } from '../data/npc-personality-traits.js';
import { NPC_MANNERISMS } from '../data/npc-mannerisms.js';
import { NPC_MOTIVATIONS } from '../data/npc-motivations.js';
import { NPC_AGENDAS } from '../data/npc-agendas.js';
import { NPC_SECRETS } from '../data/npc-secrets.js';
import { weightedPickWithPreference } from '../lib/weighted-random.js';
import { createNpcConceptDraft, updateNpcConceptDraft } from '../npc-concept.js';

/** Pick a single random appearance entry. */
export function pickNpcAppearance({ rng, preferTags = [] } = {}) {
  return weightedPickWithPreference(NPC_APPEARANCE_TRAITS, { rng, preferTags });
}

/** Pick a single random personality entry. */
export function pickNpcPersonality({ rng, preferTags = [] } = {}) {
  return weightedPickWithPreference(NPC_PERSONALITY_TRAITS, { rng, preferTags });
}

/** Pick a single random mannerism entry. */
export function pickNpcMannerism({ rng, preferTags = [] } = {}) {
  return weightedPickWithPreference(NPC_MANNERISMS, { rng, preferTags });
}

/** Pick a single random motivation entry. */
export function pickNpcMotivation({ rng, preferTags = [] } = {}) {
  return weightedPickWithPreference(NPC_MOTIVATIONS, { rng, preferTags });
}

/** Pick a single random agenda entry. */
export function pickNpcAgenda({ rng, preferTags = [] } = {}) {
  return weightedPickWithPreference(NPC_AGENDAS, { rng, preferTags });
}

/** Pick a single random secret entry. */
export function pickNpcSecret({ rng, preferTags = [] } = {}) {
  return weightedPickWithPreference(NPC_SECRETS, { rng, preferTags });
}

function composeSuggestion(personality, motivation) {
  return `Could be played as ${personality.value}, ${motivation.value} -- a GM may use this as a hook, never as a mechanical requirement.`;
}

/**
 * Roll the full set of narrative facts (all six pools, in this fixed
 * order, plus a composed `suggestion`). Returns the raw pool entries
 * AND the plain-string values a caller feeds straight into
 * `createNpcConceptDraft()`/`updateNpcConceptDraft()`.
 */
export function generateNpcNarrativeFacts({ rng, preferTags = [] } = {}) {
  const appearanceEntry = pickNpcAppearance({ rng, preferTags });
  const personalityEntry = pickNpcPersonality({ rng, preferTags });
  const mannerismEntry = pickNpcMannerism({ rng, preferTags });
  const motivationEntry = pickNpcMotivation({ rng, preferTags });
  const agendaEntry = pickNpcAgenda({ rng, preferTags });
  const secretEntry = pickNpcSecret({ rng, preferTags });
  return {
    appearanceEntry, personalityEntry, mannerismEntry, motivationEntry, agendaEntry, secretEntry,
    appearance: appearanceEntry?.value ?? '',
    personality: personalityEntry?.value ?? '',
    mannerisms: mannerismEntry?.value ?? '',
    motivation: motivationEntry?.value ?? '',
    agenda: agendaEntry?.value ?? '',
    secret: secretEntry?.value ?? '',
    suggestion: composeSuggestion(personalityEntry ?? { value: '' }, motivationEntry ?? { value: '' })
  };
}

/**
 * Generate a full NPC concept draft with narrative facts pre-filled.
 * Every base-schema field (`kind`/`name`/`speciesId`/`factionId`/...)
 * still comes straight from `input`, unchanged -- this only supplies
 * defaults for the six narrative fields when `input` doesn't already
 * set them, so a caller can override any single one explicitly.
 */
export function createGeneratedNpcConceptDraft({ rng, preferTags = [], ...input } = {}) {
  const narrative = generateNpcNarrativeFacts({ rng, preferTags });
  return createNpcConceptDraft({
    appearance: narrative.appearance,
    personality: narrative.personality,
    mannerisms: narrative.mannerisms,
    motivation: narrative.motivation,
    agenda: narrative.agenda,
    secret: narrative.secret,
    suggestion: narrative.suggestion,
    ...input
  });
}

/** Reroll ONLY the appearance field on an existing draft. */
export function rerollNpcAppearance(draft, { rng, preferTags = [] } = {}) {
  return updateNpcConceptDraft(draft, { appearance: pickNpcAppearance({ rng, preferTags })?.value ?? '' });
}

