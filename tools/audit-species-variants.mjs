#!/usr/bin/env node
/**
 * Legacy species variant audit (derived metadata only; no rules text).
 * Usage: node tools/audit-species-variants.mjs [--write]
 *
 * Joins the legacy (non-snapshot) variants in packs/species.db with the evidence recorded in
 * tools/data/species-legacy-variant-provenance.json (the printed profile each was compared against, with page
 * numbers from the Phase 4-B audit, and exactly which fields differ).
 */
import { readFileSync, writeFileSync } from 'node:fs';

const provenance = JSON.parse(readFileSync('tools/data/species-legacy-variant-provenance.json', 'utf8'));
const inPack = new Map();
for (const line of readFileSync('packs/species.db', 'utf8').split('\n').filter(Boolean)) {
  const doc = JSON.parse(line);
  for (const v of doc.system?.variants ?? []) if (v.completeSnapshot !== true) inPack.set(v.id, { species: doc.name, v });
}
const COUNT = {};
const rows = provenance.map(p => {
  const hit = inPack.get(p.variantId);
  COUNT[p.classification] = (COUNT[p.classification] ?? 0) + 1;
  const evidence = p.evidence.map(e => `${e.sourceProfileId} (${e.publication}, p.${[].concat(e.printedPages ?? []).join('/')})`).join('; ') || '—';
  const state = !hit ? 'MISSING FROM PACK' : (hit.v.supersededBy ? `superseded by \`${hit.v.supersededBy}\`` : '—') + (hit.v.legacyProvenance?.hideFromNewSelection ? '; hidden from new selections' : '; still offered');
  return `| ${p.species} | \`${p.variantId}\` | ${p.classification} | ${evidence} | ${p.differs.join('; ') || '—'} | ${state} |`;
});
const text = [
  '# Species legacy variant audit',
  '',
  'Generated by `tools/audit-species-variants.mjs` from `packs/species.db` and `tools/data/species-legacy-variant-provenance.json`',
  '(derived metadata only; no rules text). Legacy variants are never deleted, renamed or repurposed: existing actors that recorded',
  'one keep resolving it. Classifications compare each record with the printed profiles of the Phase 4-B audit.',
  '',
  '- `DUPLICATE_OF_PUBLISHED_PROFILE` / `NEAR_DUPLICATE_OF_PUBLISHED_PROFILE`: equals (or nearly equals) a verified profile; the verified profile is what new selections use.',
  '- `WITHIN_PROFILE_CHOICE`: the printed profile offers a choice (Devaronian male/female); implemented as the existing ability choice inside the verified profile.',
  '- `NO_MATCHING_PUBLISHED_PROFILE`: no audited profile prints these values (unsupported or incorrectly constructed record); no longer offered for new selections.',
  '- `UNVERIFIABLE_OUTSIDE_AUDIT`: the species is not in the Phase 4-B audit inventory, so the record cannot be verified; left as is.',
  '',
  '| Species | Variant id | Classification | Printed profile(s) compared | Differs from print | Pack state |',
  '|---|---|---|---|---|---|',
  ...rows,
  '',
  `Totals: ${provenance.length} legacy variants — ${Object.entries(COUNT).map(([k, n]) => `${n} ${k}`).join(', ')}.`,
  '',
].join('\n');
if (process.argv.includes('--write')) writeFileSync('docs/audits/swse-species-variant-audit.md', text);
else console.log(text);
