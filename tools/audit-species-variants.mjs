#!/usr/bin/env node
/**
 * Derived-metadata audit of species variants that are NOT verified publication snapshots.
 * Usage: node tools/audit-species-variants.mjs [--write]
 *
 * Reports, per species, which fields each legacy overlay variant overrides (and therefore which it inherits from
 * the base record). It does NOT classify a variant as a publication difference or a within-profile choice and does
 * not certify anything: that is a rules question for the project owner (see SPECIES-RD-011).
 */
import { readFileSync, writeFileSync } from 'node:fs';

const OVERRIDABLE = ['abilityMods', 'speed', 'size', 'movement', 'languages', 'special', 'traits', 'skillBonuses', 'naturalWeapons', 'abilityChoice'];
const present = value => value !== null && value !== undefined && value !== '' && !(Array.isArray(value) && !value.length) && !(typeof value === 'object' && !Array.isArray(value) && !Object.keys(value).length);

const rows = [];
for (const line of readFileSync('packs/species.db', 'utf8').split('\n').filter(Boolean)) {
  const doc = JSON.parse(line);
  const variants = doc.system?.variants ?? [];
  const snapshots = variants.filter(v => v.completeSnapshot === true).length;
  for (const v of variants.filter(x => x.completeSnapshot !== true)) {
    const overrides = OVERRIDABLE.filter(k => present(v[k]));
    rows.push({ species: doc.name, id: v.id, label: v.label ?? '', source: v.source ?? '', overrides, inherits: OVERRIDABLE.filter(k => !overrides.includes(k)), verifiedSnapshotsOnSpecies: snapshots });
  }
}

const out = [
  '# Species legacy variant audit',
  '',
  'Generated by `tools/audit-species-variants.mjs` from `packs/species.db` (derived metadata only; no rules text).',
  'Status of every row: **UNCERTIFIED** — not mapped to a source profile, not a verified publication, classification',
  '(publication difference vs. choice within one profile) pending project-owner ruling SPECIES-RD-011.',
  'Legacy overlay variants inherit every field they do not override from the base record.',
  '',
  '| Species | Variant id | Label | Source on record | Overrides | Inherits from base | Verified snapshots on species |',
  '|---|---|---|---|---|---|---|',
  ...rows.map(r => `| ${r.species} | \`${r.id}\` | ${r.label} | ${r.source || '—'} | ${r.overrides.join(', ') || '—'} | ${r.inherits.join(', ')} | ${r.verifiedSnapshotsOnSpecies} |`),
  '',
  `Total: ${rows.length} legacy variants on ${new Set(rows.map(r => r.species)).size} species.`,
  '',
];
const text = out.join('\n');
if (process.argv.includes('--write')) writeFileSync('docs/audits/swse-species-variant-audit.md', text);
else console.log(text);
