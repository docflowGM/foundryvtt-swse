#!/usr/bin/env node
/**
 * Mechanical completeness report for the species whose printed traits have been verified trait-by-trait
 * (tests/fixtures/species-printed-traits-*.json). Measures what the engine really does (tests/helpers/species-trait-observer.mjs)
 * and groups every trait that is not fully automated by what implementing it would take.
 *
 *   node tools/report-species-mechanical-completeness.mjs [--write]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { observeSpecies, isApplied, hasAnyEffect } from '../tests/helpers/species-trait-observer.mjs';

const fx = JSON.parse(readFileSync('tests/fixtures/species-printed-traits-core.json', 'utf8'));
const rows = [];
for (const [species, spec] of Object.entries(fx.species)) {
  const obs = await observeSpecies(species);
  for (const t of spec.traits) {
    const applied = isApplied(obs, t.mechanic);
    const any = hasAnyEffect(obs, t.mechanic);
    const measured = t.mechanic.kind === 'text' ? 'display-only' : applied ? (t.automation === 'partial' ? 'partial' : 'automated') : any ? 'incorrect' : 'display-only';
    rows.push({ species, trait: t.name, kind: t.mechanic.kind, declared: t.automation, measured, note: t.note ?? '' });
  }
}
const count = s => rows.filter(r => r.measured === s).length;
const need = r => ({
  reroll: 'Closed reroll rule (existing `reroll` rule type); skill and outcome are printed. Kel Dor Keen Force Sense and the Wookiee Skills reroll are application-limited and need the application expressed as a condition, not a plain skill reroll.',
  conditionalFeat: 'Closed `featGrant` rule with a `skillTrained` requirement (existing conditional-feat lifecycle).',
  fixedFeat: 'Closed `featGrant` rule with no requirement.',
  defense: 'Closed `defenseModifier` rule.',
  text: 'No existing engine concept: needs new engine support (senses/concealment, Take 10, weapon proficiency substitution, regeneration, breath-holding, equipment grants, trip immunity, conditional defense) or stays display-only by design.',
}[r.kind] ?? '');
const open = rows.filter(r => r.measured !== 'automated');
const byKind = {};
for (const r of open) (byKind[r.kind] ??= []).push(r);
const text = [
  '# Species mechanical completeness — Core Rulebook profiles (generated)',
  '',
  'Generated by `tools/report-species-mechanical-completeness.mjs` from `tests/fixtures/species-printed-traits-core.json`, measured against the production species-selection path.',
  'A populated field is not working mechanics: each row below is the observed engine state for one printed trait. `OFFLINE_TESTED` only; nothing here is `FOUNDRY_TESTED`.',
  '',
  `- Printed traits verified: ${rows.length} across ${Object.keys(fx.species).length} Core profiles (names, pack text key words and automation state pinned by \`tests/species-core-trait-verification.test.mjs\`).`,
  `- Automated: ${count('automated')} · Partial: ${count('partial')} · Display-only: ${count('display-only')} · Incorrectly automated: ${count('incorrect')}`,
  '',
  '## Root cause of most display-only Core traits',
  '',
  'For species without a complete-snapshot variant, `SpeciesGrantLedgerBuilder._populateTraits` adds the bare names in `special[]` first; those description-less stubs then shadow the full',
  'canonical trait text, so the closed text classifiers never see the printed rules. Only traits recognised by id (Iron Will, Great Fortitude, Lightning Reflexes, Natural Armor, Superior Defenses, Breathe Underwater, Bellow, Rage, Primitive) or whose text the legacy sidecar JSON carries (Bothan, Duros, Aqualish) are automated.',
  'Snapshot species build canonical-first. Moving verified Core records to canonical-first is the single change that unlocks the reroll, conditional-feat and fixed-feat rows below;',
  'it is deliberately NOT done here because it also activates every other non-snapshot species (including the unverified ones). It needs a per-record verification gate.',
  '',
  '## Defects found and fixed in this batch',
  '',
  '- Duros Expert Pilot and Aqualish Expert Swimmer were recorded as "keep the better result" although the printed text says the reroll must be accepted (the parser matched only "must accept"). Fixed; the same parser change flips Barabel, Chadra-Fan, O\'reenian and Tusken Raider base-record rerolls to the outcome their own text states.',
  '- Gungan Weapon Familiarity text named the electropole and a "treat as simple" mechanism; Core prints only the atlatl and the cesta, with proficiency via Weapon Proficiency (simple weapons). The electropole proficiency is printed in the Unknown Regions weapon entry (an item-level rule). Text restored.',
  '- Hutt traits: the printed "+5 species bonus" lost its bonus type and unprinted flavor was added to Supreme Stability and the Persuasion reroll. Text restored. Trandoshan Limb Regeneration said "Persistent Conditions"; the printed word is "persistent penalties". Text restored.',
  '- Not changed: Ewok "Ewokese (speak only)" has no language-restriction support (see SPECIES-RD-021).',
  '',
  '## What implementing the open rows requires',
  '',
  ...Object.entries(byKind).map(([k, list]) => `- **${k}** (${list.length}): ${need(list[0])}`),
  '',
  '## Per-trait state',
  '',
  '| Species | Trait | Mechanic | Measured state | Notes |',
  '|---|---|---|---|---|',
  ...rows.map(r => `| ${r.species} | ${r.trait} | ${r.kind} | ${r.measured} | ${r.note.replace(/\|/g, '/')} |`),
  '',
].join('\n');
if (process.argv.includes('--write')) writeFileSync('docs/audits/swse-species-mechanical-completeness.md', text); else console.log(text);
