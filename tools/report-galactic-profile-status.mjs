#!/usr/bin/env node
/**
 * Galactic Profiles v3 — per-profile certification status (generated; never hand-edited).
 *
 *   node tools/report-galactic-profile-status.mjs           write docs/audits/SWSE_Galactic_Profiles_v3_Certification_Matrix.md
 *   node tools/report-galactic-profile-status.mjs --check   fail if the committed matrix differs from a fresh run
 *
 * Status vocabulary (CLAUDE.md §6). Nothing here can produce FOUNDRY_TESTED or "ready to play": offline Node
 * evidence is capped at PARTIALLY_VERIFIED. A profile is BLOCKED when the compiler fail-closes it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadProfilesDoc, loadSchema } from '../tests/helpers/galactic-profile-fixtures.mjs';
import { createSession } from '../tests/helpers/session-harness.mjs';
import { installPackShim, installFetchShim } from '../tests/helpers/pack-shim.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'docs/audits/SWSE_Galactic_Profiles_v3_Certification_Matrix.md');
// The PRODUCTION service with V2's real registries/AbilityEngine/FeatChoiceResolver, initialised from real pack data.
installPackShim(); installFetchShim();
const { GalacticProfileRegistry } = await import('../scripts/engine/progression/profile/galactic-profile-registry.js');
const { GalacticProfileService } = await import('../scripts/engine/progression/profile/galactic-profile-service.js');
GalacticProfileRegistry._loaded = GalacticProfileRegistry.validateDocument(loadProfilesDoc(), loadSchema());

const GP = {
  RULING_BLOCKED: 'open ruling (GP-RD-001/010)', ATTRIBUTE_BASIS_UNRESOLVED: 'attribute basis unresolved (GP-RD-009)',
  SKILL_KEY_UNRESOLVED: 'skill has no V2 key (GP-RD-005)', ITEM_WITHOUT_ID: 'item has no canonical id', ITEM_UNRESOLVED: 'item not in canonical item data',
  FEAT_UNRESOLVED: 'feat not in canonical feat data', SPECIES_UNRESOLVED: 'species not in canonical data', BACKGROUND_UNRESOLVED: 'background not in canonical data',
  FORCE_POWER_UNRESOLVED: 'Force power not in canonical data',
  FEAT_PREREQUISITES_UNMET: 'V2 rejects a feat prerequisite (GP-RD-016)', TALENT_PREREQUISITES_UNMET: 'V2 rejects a talent prerequisite (GP-RD-017)',
  FEAT_SLOTS_EXCEEDED: 'more feats than V2 entitles', TALENT_SLOTS_EXCEEDED: 'more talents than V2 entitles'
};

const doc = loadProfilesDoc();
const rows = [];
const counts = { PARTIALLY_VERIFIED: 0, BLOCKED: 0 };
for (const p of doc.profiles) {
  const actor = { id: 'a', name: 'Pseudo', type: p.subtype === 'droid' ? 'droid' : (p.subtype === 'actor' ? 'character' : 'npc'), items: [], system: { level: 0, skills: {}, attributes: {}, abilities: {} }, flags: {} };
  const r = await GalacticProfileService.compileForShell({ actor, progressionSession: await createSession(p.subtype) }, p.profileId);
  const blocked = [...new Set(r.blocked.map(b => b.code))].sort();
  const status = r.ok ? 'PARTIALLY_VERIFIED' : 'BLOCKED';
  counts[status] += 1;
  const held = [];
  if (r.deferred?.forcePowers) held.push('Force powers held (Force Training not legally present)');
  if (r.deferred?.talents) held.push('talent held for V2 tree authority');
  if (r.open.some(o => o.reason === 'PUBLICATION_VERSION_REQUIRED')) held.push('species version left to player');
  const extra = [];
  if (p.subtype === 'droid' && r.ok) extra.push(`V2 quote OK ${r.resolved.droid.total} cr; installation dry-check OK`);
  if (r.diagnostics.some(d => d.code === 'ATTRIBUTE_BASIS_MOOT')) extra.push('attribute basis moot (species has no ability modifiers)');
  rows.push(`| \`${p.profileId}\` | ${p.subtype} | ${status} | ${blocked.map(c => GP[c] ?? c).join('; ') || '—'} | ${[...extra, ...held].join('; ') || '—'} |`);
}

const md = `# Galactic Profiles v3 — Certification Matrix (generated)

> Generated by \`node tools/report-galactic-profile-status.mjs\`; the test \`tests/galactic-profile-compiler.test.mjs\` pins the same outcomes. **Do not hand-edit.**

**Evidence ceiling:** offline Node only, through the PRODUCTION \`GalacticProfileService\` with V2's real registries, \`AbilityEngine\`/\`PrerequisiteChecker\`, \`FeatChoiceResolver\`, the class-grant ledger, the Feat step's entitlement rule, \`TalentCadenceEngine\`, the droid quote and installation services, initialised from the repository's real pack data. \`PARTIALLY_VERIFIED\` means the profile passed all of those and is **not** certified: Force-tree talent access (held for V2's tree authority), a live \`Actor\`/\`ActorEngine\` application and rollback, rendering, and the world database are verified only in Foundry v13 (\`FOUNDRY_TESTED\`: **0 of 41**). No profile is \`publishableAsReadyToPlay\`.

Totals: **${counts.PARTIALLY_VERIFIED} PARTIALLY_VERIFIED**, **${counts.BLOCKED} BLOCKED**, 0 FOUNDRY_TESTED, 0 ready-to-play (of ${doc.profiles.length}).

| Profile | Subtype | Status | Blocked by (fail-closed) | Notes |
|---|---|---|---|---|
${rows.join('\n')}
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (current !== md) { console.error('DRIFT: certification matrix differs from a fresh run'); process.exit(1); }
  console.log('certification matrix is current');
} else {
  fs.writeFileSync(OUT, md);
  console.log(`wrote ${path.relative(ROOT, OUT)} — ${counts.PARTIALLY_VERIFIED} partially verified, ${counts.BLOCKED} blocked`);
}
