#!/usr/bin/env node
/**
 * Species in packs/species.db that are not part of the Phase 4-B audit inventory (neither a bulk-hydrated profile nor a
 * Core / multi-publication profile covered by the committed audit fixtures). For each, report the pack's recorded source and
 * whether a printed "<Name> Species Traits" block exists in the local sourcebook text. Derived metadata only: it classifies
 * nothing as valid or invalid and never changes data.
 *
 *   node tools/audit-species-outside-inventory.mjs [--write]
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const fixtures = ['tests/fixtures/species-profile-expectations.json', 'tests/fixtures/species-audit-numbers.json']
  .map(f => JSON.parse(readFileSync(f, 'utf8')));
const audited = new Set(fixtures.flatMap(f => Object.values(f).map(e => e.species)));
// Audited profiles that are technical holds (listed in the generated status report) are inside the inventory too.
for (const m of readFileSync('docs/audits/swse-species-implementation-status.md', 'utf8').matchAll(/^\| [A-Z0-9-]+ (.+?) \| technical \|/gm)) audited.add(m[1]);
const books = readdirSync('reference/sourcebooks').filter(f => f.endsWith('.txt'))
  .map(f => ({ name: f.replace(/_djvu\.txt$/, ''), lines: readFileSync(`reference/sourcebooks/${f}`, 'utf8').split('\n') }));
const norm = s => s.toLowerCase().replace(/[^a-z0-9]/g, '');

const provenance = JSON.parse(readFileSync('tools/data/species-outside-provenance.json', 'utf8'));
const rows = [];
for (const line of readFileSync('packs/species.db', 'utf8').split('\n').filter(Boolean)) {
  const doc = JSON.parse(line);
  if (audited.has(doc.name)) continue;
  const key = norm(doc.name);
  const hits = [];
  for (const book of books) {
    book.lines.forEach((text, i) => {
      const t = norm(text);
      if (t.length > 120) return;
      const heading = t.includes(`${key}speciestraits`) || t.includes(`${key}racialtraits`) || t.includes(`${key}ssharethefollowing`) || t.includes(`${key}sharethefollowing`);
      if (heading) hits.push(`${book.name} line ${i + 1}`);
    });
  }
  rows.push({
    name: doc.name, source: doc.system?.source ?? '—', droid: !!doc.system?.speciesActsAsDroid || /droid/i.test(doc.name),
    variants: (doc.system?.variants ?? []).map(v => v.id), printed: hits,
    prov: provenance[doc.name] ?? null,
  });
}
const found = rows.filter(r => r.printed.length);
const byClass = {};
for (const r of rows) (byClass[r.prov?.classification ?? 'UNCLASSIFIED'] ??= []).push(r.name);
const esc = v => String(v ?? '').replace(/\|/g, '/');
const text = [
  '# Species outside the Phase 4-B audit inventory (generated)',
  '',
  'Generated by `tools/audit-species-outside-inventory.mjs` from `tools/data/species-outside-provenance.json` (manual provenance review against the local OCR text).',
  'Nothing here is declared valid or invalid, nothing is deleted, renamed or merged, and none of these species is certified. OCR text is a search layer:',
  '"not found locally" is not proof that no published rules exist; the PDFs remain the final authority and are not available in this environment. Printed page numbers are not',
  'recoverable from the text export, so evidence cites text-file line numbers.',
  '',
  `- ${rows.length} species are outside the audited inventory.`,
  `- ${found.length} have a printed "<Name> Species Traits" block found by heading search (Replica Droid); manual review found one more near-Human template (O'reenian) with no traits block.`,
  '',
  '## Classification summary',
  '',
  ...Object.entries(byClass).sort().map(([c, n]) => `- **${c}** (${n.length}): ${n.join(', ')}`),
  '',
  '## Per-species evidence',
  '',
  '| Species | Pack source | Classification | Evidence (local text) | Notes |',
  '|---|---|---|---|---|',
  ...rows.map(r => `| ${r.name}${r.droid ? ' (droid)' : ''} | ${esc(r.source)} | ${r.prov?.classification ?? 'UNCLASSIFIED'} | ${esc(r.prov?.evidence)} | ${esc(r.prov?.note)}${r.variants.length ? ` Legacy variants: ${r.variants.join(', ')}.` : ''} |`),
  '',
].join('\n');
if (process.argv.includes('--write')) writeFileSync('docs/audits/swse-species-outside-inventory.md', text); else console.log(text);
