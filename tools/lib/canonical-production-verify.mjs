// Phase 5C-18..27: parity verification of the two operational canonical corpora against everything generated from them.
// Pure over an `io` object ({ read(rel) -> string, exists(rel) -> bool }) so the negative tests can feed mutated inputs.
import crypto from 'node:crypto';
import { verifyLossless as verifyFeatCorpus, EXPECTED as FEATS } from '../build-canonical-feats.mjs';
import { generate as generateFeats, OUT as FEAT_OUT } from '../build-feat-production.mjs';
import { verifyLossless as verifyWeaponCorpus, EXPECTED as WEAPONS } from '../build-canonical-weapons.mjs';
import { buildProduction, MASTER_PACK } from '../build-weapon-production.mjs';
import { buildRegistry, serialize as serializeRegistry } from '../build-weapon-runtime-registry.mjs';
import { certifiedVocabulary } from './item-weapons-phase-4h.mjs';

export const CANONICAL_FEATS = 'data/canonical/feats.json';
export const CANONICAL_WEAPONS = 'data/canonical/weapons.json';
export const EXPECTED = { feats: FEATS, weapons: WEAPONS, talents: 1187 };
const LEGACY_PROFICIENCY_ALIAS_FILE = 'scripts/engine/feats/legacy-weapon-proficiency-alias.js';

const attempt = (errs, label, fn, dflt) => { try { return fn(); } catch (e) { errs.push(`${label}: ${e.message}`); return dflt; } };
const lines = (t) => t.split('\n').filter(Boolean);

/** Feat parity: 353 canonical = 353 production, exact generated bytes, stamps, semantic parity, aliases, no retired ids. */
export function verifyFeats(io, opts = {}) {
  const errs = [];
  const corpus = JSON.parse(io.read(CANONICAL_FEATS));
  if (!opts.skipLossless) errs.push(...verifyFeatCorpus(corpus).map((e) => `feat corpus: ${e}`));
  const ids = corpus.identities.map((x) => x.canonicalId);
  if (corpus.identities.length !== EXPECTED.feats) errs.push(`feat corpus has ${corpus.identities.length} identities, expected ${EXPECTED.feats}`);
  if (new Set(ids).size !== ids.length) errs.push('feat corpus: duplicate canonical id');
  const docs = lines(io.read(FEAT_OUT.pack)).map((l) => JSON.parse(l));
  const packIds = docs.map((d) => d._id);
  if (new Set(packIds).size !== packIds.length) errs.push('feat pack: duplicate _id');
  for (const id of ids) if (!packIds.includes(id)) errs.push(`feat pack: missing canonical feat ${id}`);
  for (const id of packIds) if (!ids.includes(id)) errs.push(`feat pack: unexpected feat ${id}`);
  if (docs.length !== EXPECTED.feats) errs.push(`feat pack has ${docs.length} documents, expected ${EXPECTED.feats}`);
  const catalog = JSON.parse(io.read(FEAT_OUT.catalog));
  if (catalog.length !== docs.length || JSON.stringify(catalog) !== JSON.stringify(docs)) errs.push('feat catalog compatibility projection differs from the pack');
  const expected = attempt(errs, 'feat generator', () => generateFeats(corpus), {});
  for (const [f, t] of Object.entries(expected)) if (io.read(f) !== t) errs.push(`generated feat output ${f} differs from data/canonical/feats.json (hand-edited or stale)`);
  const byId = new Map(corpus.identities.map((x) => [x.canonicalId, x]));
  const vocab = new Set(JSON.parse(io.read('data/audits/talent-feat-phase3-final-semantic-authority.json')).vocabulary ?? []);
  let semantic = 0;
  for (const d of docs) {
    const c = byId.get(d._id);
    if (!c) continue;
    const st = d.flags?.swse?.canonicalFeat;
    if (st?.identityKey !== c.identityKey || st?.canonicalId !== c.canonicalId) errs.push(`feat ${d.name}: missing/wrong flags.swse.canonicalFeat identity stamp`);
    const tags = d.system?.semanticTags ?? [];
    if (JSON.stringify(tags) !== JSON.stringify(c.semantic.finalTags)) errs.push(`feat ${d.name}: system.semanticTags differ from the certified assignment`);
    else semantic++;
    for (const t of tags) if (vocab.size && !vocab.has(t)) errs.push(`feat ${d.name}: unknown semantic tag ${t}`);
    if (d.system?.source !== c.primaryPublication.source || d.system?.page !== c.primaryPublication.page) errs.push(`feat ${d.name}: source/page differ from certified provenance`);
    if (d.name !== c.displayName) errs.push(`feat ${d.name}: name differs from certified display name ${c.displayName}`);
  }
  // aliases: complete, derivative -> canonical Weapon Proficiency + explicit choice, retired ids absent from the pack
  const aliases = JSON.parse(io.read(FEAT_OUT.aliases));
  const retired = new Set(corpus.retiredProductionRecords.map((r) => r.oldId));
  for (const r of corpus.retiredProductionRecords) {
    const a = aliases.aliases.find((x) => x.oldId === r.oldId);
    if (!a) { errs.push(`feat alias map: missing alias for ${r.oldName} (${r.oldId})`); continue; }
    if (r.disposition === 'IMPLEMENTATION_DERIVATIVE_MIGRATED_TO_CHOICE') {
      if (a.canonicalFeatId !== corpus.counts.weaponProficiencyCanonicalId || !a.choice?.value) errs.push(`feat alias map: derivative ${r.oldName} has no canonical Weapon Proficiency + choice mapping`);
      if (!byId.has(a.canonicalFeatId)) errs.push(`feat alias map: derivative ${r.oldName} targets a non-canonical feat`);
    }
  }
  for (const id of packIds) if (retired.has(id)) errs.push(`feat pack still carries retired feat ${id}`);
  if (aliases.aliases.length !== corpus.retiredProductionRecords.length) errs.push('feat alias map size differs from the retired record list');
  // runtime compat table must equal the alias map
  const compat = io.read(LEGACY_PROFICIENCY_ALIAS_FILE);
  const groups = new Set(aliases.aliases.filter((a) => a.choice).map((a) => a.choice.value));
  for (const g of groups) if (!compat.includes(`'${g}'`)) errs.push(`legacy weapon-proficiency compat table lacks choice ${g}`);
  if (!compat.includes(corpus.counts.weaponProficiencyCanonicalId)) errs.push('legacy weapon-proficiency compat table targets a different canonical id');
  return { errors: errs, counts: { canonical: ids.length, production: docs.length, semanticMatched: semantic, retired: retired.size } };
}

const slimWeaponTags = (r) => JSON.stringify({ c: r.semantic?.categories, t: r.semantic?.tags });

/** Weapon parity: 203 canonical = 203 production, exact generated bytes, registry, aliases, projection, semantic parity. */
export function verifyWeapons(io, opts = {}) {
  const errs = [];
  const corpus = JSON.parse(io.read(CANONICAL_WEAPONS));
  if (!opts.skipLossless) errs.push(...verifyWeaponCorpus(corpus).map((e) => `weapon corpus: ${e}`));
  const ids = corpus.identities.map((x) => x.production.id);
  if (corpus.identities.length !== EXPECTED.weapons) errs.push(`weapon corpus has ${corpus.identities.length} identities, expected ${EXPECTED.weapons}`);
  if (new Set(ids).size !== ids.length) errs.push('weapon corpus: duplicate production id');
  const { files } = attempt(errs, 'weapon generator', () => buildProduction(corpus), { files: {} });
  for (const [f, t] of Object.entries(files)) if (!io.exists(f) || io.read(f) !== t) errs.push(`generated weapon output ${f} differs from data/canonical/weapons.json (hand-edited or stale)`);
  const master = lines(io.read(MASTER_PACK)).map((l) => JSON.parse(l));
  const weaponDocs = master.filter((d) => d.flags?.swse?.canonicalWeapon);
  const packIds = weaponDocs.map((d) => d._id);
  if (new Set(packIds).size !== packIds.length) errs.push('weapon pack: duplicate _id');
  for (const id of ids) if (!packIds.includes(id)) errs.push(`weapon pack: missing canonical weapon ${id}`);
  for (const id of packIds) if (!ids.includes(id)) errs.push(`weapon pack: unexpected weapon ${id}`);
  const byId = new Map(corpus.identities.map((x) => [x.production.id, x]));
  for (const d of weaponDocs) {
    const c = byId.get(d._id);
    if (c && d.flags.swse.canonicalWeapon.identityKey !== c.identityKey) errs.push(`weapon ${d.name}: lost/changed identity stamp`);
    if (c && d.name !== c.canonicalName) errs.push(`weapon ${d.name}: name differs from canonical name`);
  }
  const retiredIds = new Set(corpus.retiredProductionRecords.map((r) => r.oldId));
  const aliases = JSON.parse(io.read('data/migrations/weapon-canonical-aliases.json'));
  for (const r of corpus.retiredProductionRecords) if (!aliases.retired.some((a) => a.oldId === r.oldId)) errs.push(`weapon alias map: missing retired weapon ${r.oldName} (${r.oldId})`);
  for (const id of packIds) if (retiredIds.has(id) && !ids.includes(id)) errs.push(`weapon pack still carries retired weapon ${id}`);
  // runtime registry
  const reg = attempt(errs, 'weapon registry generator', () => serializeRegistry(buildRegistry((f) => io.read(f))), null);
  if (reg !== null && io.read('data/weapons/canonical-weapon-registry.json') !== reg) errs.push('weapon runtime registry differs from data/canonical/weapons.json');
  const regJson = JSON.parse(io.read('data/weapons/canonical-weapon-registry.json'));
  if (regJson.identities.length !== EXPECTED.weapons) errs.push(`weapon registry has ${regJson.identities.length} identities`);
  // semantic parity: registry semantic block == corpus == certified vocabulary
  const vocab = certifiedVocabulary();
  const distinct = new Set();
  let semantic = 0;
  for (const c of corpus.identities) {
    const r = regJson.identities.find((x) => x.identityKey === c.identityKey);
    if (!r || slimWeaponTags(r) !== slimWeaponTags(c)) errs.push(`weapon ${c.canonicalName}: registry semantic block differs from canonical`);
    else semantic++;
    for (const t of Object.values(c.semantic?.tags ?? {}).flatMap((v) => (Array.isArray(v) ? v.map((x) => (typeof x === 'string' ? x : x?.tag)) : [])).filter(Boolean)) { distinct.add(t); if (!vocab.has(t)) errs.push(`weapon ${c.canonicalName}: semantic tag ${t} outside the certified vocabulary`); }
  }
  return { errors: errs, counts: { canonical: ids.length, production: weaponDocs.length, registry: regJson.identities.length, semanticMatched: semantic, distinctTags: distinct.size, vocabulary: vocab.size } };
}

export const sha256 = (t) => crypto.createHash('sha256').update(t).digest('hex');
