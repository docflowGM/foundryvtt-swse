import assert from 'node:assert/strict';
import { registerFoundryPathLoader } from './helpers/foundry-shim/register.mjs';
import { installFoundryShimGlobals } from './helpers/foundry-shim/globals.mjs';
globalThis.window = globalThis.window || { location: { hostname: 'localhost' } };
registerFoundryPathLoader();
installFoundryShimGlobals();
globalThis.game.user = { id: 'gm', isGM: true };
globalThis.ui = { notifications: { info() {}, warn() {}, error() {} } };
globalThis.Hooks = globalThis.Hooks ?? { callAll: () => {}, on: () => {} };
const { DejarikEngine } = await import('../scripts/games/games/dejarik/dejarik-engine.js');
const { GameSessionStore } = await import('../scripts/games/game-session-store.js');
const { GameNotificationService } = await import('../scripts/games/game-notification-service.js');
const { DEJARIK_PIECES } = await import('../scripts/games/games/dejarik/dejarik-pieces.js');
GameNotificationService.emitSessionUpdated = () => {};
let session = { id: 's1', gameId: 'dejarik', seats: [
  { seatId: 'p', type: 'player', displayName: 'P', recipientId: 'u1' },
  { seatId: 'a', type: 'ai', displayName: 'AI', aiProfile: 'medium' }], log: [] };
GameSessionStore.getSession = () => session;
GameSessionStore.upsertSession = async (s) => { session = s; return s; };
const act = (action, payload = {}, seatId = 'p') => DejarikEngine.submitAction({ sessionId: 's1', seatId, action, payload });
const ids = DEJARIK_PIECES.map(p => p.id);
const st = () => session.gameState;

let r = await act('select-monster', { monsterId: ids[0] });
assert.equal(r.ok, true, `first selection must succeed: ${r.error}`);
assert.deepEqual(st().draft.selectedMonsterIds, [ids[0]]);
assert.equal(st().phase, 'draft');
for (const id of ids.slice(1, 4)) assert.equal((await act('select-monster', { monsterId: id })).ok, true);
assert.equal(st().draft.selectedMonsterIds.length, 4);
assert.equal((await act('select-monster', { monsterId: ids[4] })).ok, false, 'fifth refused by the engine');
assert.equal(st().draft.selectedMonsterIds.length, 4);
assert.equal((await act('select-monster', { monsterId: 'nope' })).ok, false, 'unknown id rejected');
assert.equal((await act('select-monster', { monsterId: ids[0] })).ok, true, 'toggle removes');
assert.equal(st().draft.selectedMonsterIds.length, 3);
assert.equal((await act('deploy-team')).ok, false, 'deploy refused below four');
assert.equal(st().phase, 'draft');
assert.equal((await act('clear-draft')).ok, true);
assert.equal(st().draft.selectedMonsterIds.length, 0);
assert.equal((await act('move', { pieceId: 'x' })).ok, false, 'board action refused while drafting');
assert.equal((await act('select-monster', { monsterId: ids[0] }, 'a')).ok, false, 'non-drafting seat refused');
for (const id of ids.slice(0, 4)) await act('select-monster', { monsterId: id });
r = await act('deploy-team');
assert.equal(r.ok, true, r.error);
assert.equal(st().phase, 'playing');
const owners = Object.values(st().pieces).reduce((m, p) => (m[p.ownerSeatId] = (m[p.ownerSeatId] || 0) + 1, m), {});
assert.deepEqual(owners, { p: 4, a: 4 });
const spaces = Object.values(st().pieces).map(p => p.spaceId); assert.equal(new Set(spaces).size, 8);
const again = await act('deploy-team'); assert.equal(again.ok, false, 'replayed deploy rejected');
assert.match(again.error, /draft/i);
assert.equal((await act('select-monster', { monsterId: ids[0] })).ok, false, 'draft closed during play');
console.log('dejarik draft dispatch: ok');
